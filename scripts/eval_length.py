"""Evaluate agents trained on 25-step episodes on longer episodes (no retraining).

Writes results/length/summary.json, per-matchup CSVs and presentation/generated/length_table.tex.
  uv run python scripts/eval_length.py runs/v2_long_s0/final.pt runs/v2_long_s1/final.pt runs/v2_long_s2/final.pt
"""

from __future__ import annotations

import argparse
import json
from multiprocessing import Pool
from pathlib import Path

from eval_baselines import evaluate, num, spec_name
from worldcomm import summarize, write_csv

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "length"
LENGTHS = (25, 50, 100)


def run(job):
    team, T, adv, good, episodes = job
    recs = evaluate(adv, good, episodes, max_cycles=T)
    write_csv(recs, OUT / f"{spec_name(adv)}_vs_{spec_name(good)}_T{T}.csv", adv=adv, good=good, max_cycles=T)
    return {"team": team, "T": T, "adv": adv, "good": good, **summarize(recs)}


def mean(rows, team, T, key):
    vals = [r[key] for r in rows if r["team"] == team and r["T"] == T]
    return sum(vals) / len(vals)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("checkpoints", nargs="+")
    p.add_argument("--episodes", type=int, default=1000)
    p.add_argument("--procs", type=int, default=3)
    args = p.parse_args()
    jobs = []
    for T in LENGTHS:
        jobs.append(("heur", T, "heuristic", "heuristic", args.episodes))
        for ck in args.checkpoints:
            jobs += [("adv", T, f"mappo:{ck}", "heuristic", args.episodes),
                     ("good", T, "heuristic", f"mappo:{ck}", args.episodes)]
    OUT.mkdir(parents=True, exist_ok=True)
    with Pool(args.procs) as pool:
        rows = pool.map(run, jobs)
    (OUT / "summary.json").write_text(json.dumps(rows, indent=2))

    # table: mean catches per episode (the % of episodes with a catch saturates at 100% for long episodes)
    lines = ["% generated by scripts/eval_length.py - do not edit",
             "\\begin{tabular}{@{}lrrr@{}}", "\\toprule",
             "długość epizodu & heurystyka vs heurystyka & drap. MAPPO vs heur. ofiary & heur. drap. vs ofiary MAPPO \\\\",
             "\\midrule"]
    for T in LENGTHS:
        h, a, g = (mean(rows, t, T, "catches") for t in ("heur", "adv", "good"))
        lines.append(f"{T} kroków & {num(h, 2)} & {num(a, 2)} ({num(a / h, 2)}×) & {num(g, 2)} ({num(g / h, 2)}×) \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    tab = ROOT / "presentation" / "generated" / "length_table.tex"
    tab.write_text("\n".join(lines) + "\n")
    for line in lines[5:-2]:
        print(line)
    print("saved", tab)


if __name__ == "__main__":
    main()
