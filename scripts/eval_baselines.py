"""Evaluate fixed team policies against each other on simple_world_comm.

Logs every episode to results/baselines/<name>.csv, writes results/baselines/summary.json,
and the slide table presentation/generated/baseline_table.tex.
With --agents, only the --extra matchups are run and the output goes to results/agents/ and
presentation/generated/agent_table.tex instead, leaving the baseline files untouched.
Policy specs: random | heuristic | mappo:<checkpoint.pt> (see worldcomm.policies.make_policy).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from worldcomm import EpisodeStats, make_env, summarize, write_csv
from worldcomm.policies import TeamMix, make_policy

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "baselines"

MATCHUPS = [("random", "random"), ("heuristic", "random"), ("random", "heuristic"), ("heuristic", "heuristic")]
FOREST_SWEEP = [0, 2, 4]
LABEL = {"random": "losowi", "heuristic": "heurystyczni"}


EVAL_SEED0 = 0


def evaluate(adv: str, good: str, episodes: int, seed0: int = EVAL_SEED0, **env_kw) -> list[dict]:
    env = make_env(**env_kw)
    counts = {k: v for k, v in env_kw.items() if k != "max_cycles"}
    policy = TeamMix(make_policy(adv, env, seed=1, **counts), make_policy(good, env, seed=2, **counts))
    records = []
    for ep in range(episodes):
        obs, _ = env.reset(seed=seed0 + ep)
        st = EpisodeStats()
        st.reset(env)
        while env.agents:
            actions = policy(obs)
            obs, rew, _, _, _ = env.step(actions)
            st.step(env, actions, rew)
        records.append(st.finish())
    env.close()
    return records


def spec_name(spec: str) -> str:
    """'heuristic' -> 'heuristic'; 'mappo:runs/x/final.pt' -> 'mappo-x-final' (unique per checkpoint)."""
    if ":" not in spec:
        return spec
    kind, path = spec.split(":", 1)
    return f"{kind}-{Path(path).parent.name}-{Path(path).stem}"


def run_all(episodes: int, extra: list[tuple[str, str]], out: Path, baselines: bool = True) -> list[dict]:
    rows = []
    base = MATCHUPS if baselines else []
    for k, (adv, good) in enumerate(base + extra):
        recs = evaluate(adv, good, episodes)
        name = f"{spec_name(adv)}_vs_{spec_name(good)}_f2"
        if baselines and k >= len(base):
            name = "extra_" + name  # never overwrite a baseline log
        write_csv(recs, out / f"{name}.csv", adv=adv, good=good, num_forests=2)
        rows.append({"adv": adv, "good": good, "num_forests": 2, **summarize(recs)})
        print(name, {k: round(v, 3) for k, v in rows[-1].items() if isinstance(v, float) and not k.endswith("_std")})
    for nf in FOREST_SWEEP if baselines else []:
        if nf == 2:
            continue
        for adv, good in [("random", "random"), ("heuristic", "heuristic")]:
            recs = evaluate(adv, good, episodes, num_forests=nf)
            name = f"{adv}_vs_{good}_f{nf}"
            write_csv(recs, OUT / f"{name}.csv", adv=adv, good=good, num_forests=nf)
            rows.append({"adv": adv, "good": good, "num_forests": nf, **summarize(recs)})
            print(name, {k: round(v, 3) for k, v in rows[-1].items() if isinstance(v, float) and not k.endswith("_std")})
    return rows


def parse_matchup(spec: str) -> tuple[str, str]:
    """'adv_spec,good_spec' -> (adv_spec, good_spec)."""
    adv, good = spec.split(",", 1)
    return adv, good


def pct(x: float) -> str:
    return f"{100 * x:.0f}\\%"


def num(x: float, d: int = 1) -> str:
    return f"{x:.{d}f}".replace(".", ",")


def write_table(rows: list[dict], path: Path):
    lines = [
        "% generated by scripts/eval_baselines.py - do not edit",
        "\\begin{tabular}{@{}llrrrrr@{}}",
        "\\toprule",
        "drapieżnicy & ofiary & nagroda drap. & nagroda ofiar & złapania & epiz. ze złapaniem & ofiary poza areną \\\\",
        "\\midrule",
    ]
    for r in rows:
        if r["num_forests"] != 2:
            continue
        lines.append(
            f"{LABEL.get(r['adv'], 'MAPPO')} & {LABEL.get(r['good'], 'MAPPO')} & {num(r['adv_return'])} & "
            f"{num(r['good_return'])} & {num(r['catches'], 2)} & {pct(r['caught'])} & {pct(r['out_frac'])} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}"]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    print("saved", path)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--episodes", type=int, default=1000)
    p.add_argument("--replot", action="store_true")
    p.add_argument("--extra", nargs="*", default=[], help="extra matchups as adv,good specs")
    p.add_argument("--agents", action="store_true", help="run only --extra, write results/agents + agent_table.tex")
    args = p.parse_args()
    out = ROOT / "results" / ("agents" if args.agents else "baselines")
    table = "agent_table.tex" if args.agents else "baseline_table.tex"
    summary = out / "summary.json"
    if args.replot:
        rows = json.loads(summary.read_text())
    else:
        rows = run_all(args.episodes, [parse_matchup(m) for m in args.extra], out, baselines=not args.agents)
        out.mkdir(parents=True, exist_ok=True)
        summary.write_text(json.dumps(rows, indent=2))
    write_table(rows, ROOT / "presentation" / "generated" / table)


if __name__ == "__main__":
    main()
