"""Compare self-play configurations over seeds (runs/<config>_s<seed>/progress.csv).

Final score of a run = mean of its last 5 evaluations (512 episodes each, against
heuristic and random opponents); the table shows mean ± std over seeds.

  uv run python scripts/compare_runs.py mappo_h128 ippo_h128 mappo_h64 mappo_h256 mappo_h256x3
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from worldcomm.plotting import COLORS, MUTED, style_axes

ROOT = Path(__file__).resolve().parents[1]
LABELS = {
    "mappo_h128": "MAPPO 2×128", "ippo_h128": "IPPO 2×128", "mappo_h64": "MAPPO 2×64",
    "mappo_h256": "MAPPO 2×256", "mappo_h256x3": "MAPPO 3×256",
}
# (column, short name)
METRICS = [
    ("eval_adv_vs_heuristic_adv_return", "nagr. drap. vs heur."),
    ("eval_adv_vs_heuristic_caught", "drap. vs heur.: złapane"),
    ("eval_adv_vs_random_caught", "drap. vs los.: złapane"),
    ("eval_good_vs_heuristic_caught", "ofiary vs heur.: złapane"),
    ("eval_good_vs_heuristic_good_return", "nagr. ofiar vs heur."),
    ("eval_good_vs_random_caught", "ofiary vs los.: złapane"),
]


def load(config: str) -> list[pd.DataFrame]:
    out = []
    for d in sorted(ROOT.glob(f"runs/{config}_s*")):
        f = d / "progress.csv"
        if f.exists() and (d / "final.pt").exists():  # finished runs only
            df = pd.read_csv(str(f)).dropna(subset=["eval_adv_vs_heuristic_caught"])
            if len(df):
                out.append(df)
    return out


def final(df: pd.DataFrame, col: str) -> float:
    return float(df[col].tail(5).mean())


def fmt(vals: list[float], col: str) -> str:
    pct = col.endswith("caught")
    v = np.array(vals) * (100 if pct else 1)
    s = f"{v.mean():.0f}" if pct else f"{v.mean():.1f}"
    if len(v) > 1:
        s += f" ± {v.std():.0f}" if pct else f" ± {v.std():.1f}"
    return (s + ("%" if pct else "")).replace(".", ",")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("configs", nargs="+")
    p.add_argument("--out", default="presentation/figures/compare.pdf")
    p.add_argument("--table", default="presentation/generated/compare_table.tex")
    args = p.parse_args()
    runs = {c: load(c) for c in args.configs}

    # ---- table (stdout + LaTeX + json)
    rows = []
    for c, dfs in runs.items():
        if not dfs:
            continue
        row = {"config": c, "seeds": len(dfs), "steps_M": round(min(d.env_steps.iloc[-1] for d in dfs) / 1e6, 1)}
        for col, _ in METRICS:
            row[col] = [final(d, col) for d in dfs]
        rows.append(row)
    print(f"{'config':14s} seeds  steps  " + "  ".join(f"{n:>24s}" for _, n in METRICS))
    for r in rows:
        print(f"{r['config']:14s} {r['seeds']:5d} {r['steps_M']:5.1f}M  "
              + "  ".join(f"{fmt(r[c], c):>24s}" for c, _ in METRICS))
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "compare.json").write_text(json.dumps(rows, indent=2))

    cols = [(c, n) for c, n in METRICS if c in (
        "eval_adv_vs_heuristic_adv_return", "eval_adv_vs_heuristic_caught",
        "eval_good_vs_heuristic_caught", "eval_good_vs_heuristic_good_return")]
    lines = ["% generated by scripts/compare_runs.py - do not edit",
             "\\begin{tabular}{@{}l" + "r" * len(cols) + "@{}}", "\\toprule",
             "konfiguracja & " + " & ".join(n.replace("%", "\\%") for _, n in cols) + " \\\\", "\\midrule"]
    for r in rows:
        lines.append(LABELS.get(r["config"], r["config"]) + " & "
                     + " & ".join(fmt(r[c], c).replace("%", "\\%").replace("±", "$\\pm$") for c, _ in cols) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    tab = ROOT / args.table
    tab.parent.mkdir(parents=True, exist_ok=True)
    tab.write_text("\n".join(lines) + "\n")
    print("saved", tab)

    # ---- curves: mean over seeds, band = min to max
    base = {(r["adv"], r["good"]): r for r in json.loads((ROOT / "results/baselines/summary.json").read_text())
            if r["num_forests"] == 2}
    fig, axes = plt.subplots(1, 2, figsize=(7.6, 3.4), dpi=150)
    panels = [("eval_adv_vs_heuristic_caught", "Drapieżnicy vs heur. ofiary", "heurystyczni drapieżnicy"),
              ("eval_good_vs_heuristic_caught", "Ofiary vs heur. drapieżnicy (mniej = lepiej)", "heurystyczne ofiary")]
    for ax, (col, title, b_label) in zip(axes, panels):
        for i, (c, dfs) in enumerate(runs.items()):
            if not dfs:
                continue
            n = min(len(d) for d in dfs)
            x = dfs[0].env_steps.values[:n] / 1e6
            y = np.stack([100 * d[col].values[:n] for d in dfs])
            y = pd.DataFrame(y.T).rolling(3, min_periods=1).mean().values.T  # light smoothing
            color = COLORS[i % len(COLORS)]
            ax.plot(x, y.mean(0), color=color, lw=1.8, label=f"{LABELS.get(c, c)} ({len(dfs)})")
            if len(dfs) > 1:
                ax.fill_between(x, y.min(0), y.max(0), color=color, alpha=0.15, lw=0)
        ax.axhline(100 * base[("heuristic", "heuristic")]["caught"], color=MUTED, lw=1.2, ls="--", label=b_label)
        style_axes(ax, title, "% epizodów ze złapaniem")
    for ax in axes:
        ax.set_ylim(50, 100)
    handles, labels = axes[0].get_legend_handles_labels()
    labels[-1] = "heurystyka"  # dashed line: heuristic predators (left) / heuristic prey (right)
    fig.legend(handles, labels, loc="lower center", ncol=3, fontsize=7, frameon=False)
    fig.tight_layout(rect=(0, 0.12, 1, 1))
    out = ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out)
    print("saved", out)


if __name__ == "__main__":
    main()
