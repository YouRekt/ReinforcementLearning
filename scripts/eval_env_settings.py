"""Compare MAPPO agents trained on different environment settings (same budget: 20M steps).

Each setting is evaluated in its own environment: MAPPO predators vs heuristic prey, heuristic
predators vs MAPPO prey, and heuristic vs heuristic as the reference for that setting.
Writes results/env_settings/summary.json, per-matchup CSVs and presentation/generated/env_table.tex.
  uv run python scripts/eval_env_settings.py
"""

from __future__ import annotations

import argparse
import json
from multiprocessing import Pool
from pathlib import Path

from eval_baselines import evaluate, num, spec_name
from worldcomm import summarize, write_csv

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "env_settings"
# (label, run prefix in runs/, env kwargs)
SETTINGS = [
    ("2 lasy, 25 kroków (domyślne)", "mappo_h128", {}),
    ("0 lasów", "env_f0", {"num_forests": 0}),
    ("4 lasy", "env_f4", {"num_forests": 4}),
    ("epizod 50 kroków", "env_ep50", {"max_cycles": 50}),
]


def run(job):
    label, team, adv, good, kw, episodes = job
    recs = evaluate(adv, good, episodes, **kw)
    tag = "_".join(f"{k}{v}" for k, v in kw.items()) or "default"
    write_csv(recs, OUT / f"{spec_name(adv)}_vs_{spec_name(good)}_{tag}.csv", adv=adv, good=good, **kw)
    return {"setting": label, "team": team, "adv": adv, "good": good, **kw, **summarize(recs)}


def mean(rows, label, team, key):
    vals = [r[key] for r in rows if r["setting"] == label and r["team"] == team]
    return sum(vals) / len(vals)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--episodes", type=int, default=1000)
    p.add_argument("--procs", type=int, default=6)
    args = p.parse_args()
    jobs = []
    for label, prefix, kw in SETTINGS:
        jobs.append((label, "heur", "heuristic", "heuristic", kw, args.episodes))
        for ck in sorted(ROOT.glob(f"runs/{prefix}_s*/final.pt")):
            spec = f"mappo:{ck.relative_to(ROOT)}"
            jobs += [(label, "adv", spec, "heuristic", kw, args.episodes),
                     (label, "good", "heuristic", spec, kw, args.episodes)]
    OUT.mkdir(parents=True, exist_ok=True)
    with Pool(args.procs) as pool:
        rows = pool.map(run, jobs)
    (OUT / "summary.json").write_text(json.dumps(rows, indent=2))

    # catches per episode, and relative to heuristic vs heuristic in the same setting
    lines = ["% generated by scripts/eval_env_settings.py - do not edit",
             "\\begin{tabular}{@{}lrrrr@{}}", "\\toprule",
             "ustawienie & seedy & heur. vs heur. & drap. MAPPO vs heur. ofiary & heur. drap. vs ofiary MAPPO \\\\",
             "\\midrule"]
    for label, *_ in SETTINGS:
        n = sum(r["setting"] == label and r["team"] == "adv" for r in rows)
        if not n:
            continue
        h, a, g = (mean(rows, label, t, "catches") for t in ("heur", "adv", "good"))
        lines.append(f"{label} & {n} & {num(h, 2)} & {num(a, 2)} ({num(a / h, 2)}×) & {num(g, 2)} ({num(g / h, 2)}×) \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    tab = ROOT / "presentation" / "generated" / "env_table.tex"
    tab.write_text("\n".join(lines) + "\n")
    for line in lines[5:-2]:
        print(line)
    for label, *_ in SETTINGS:
        if any(r["setting"] == label and r["team"] == "adv" for r in rows):
            print(label, {t: f"caught {100 * mean(rows, label, t, 'caught'):.0f}%  hidden {100 * mean(rows, label, t, 'hidden_frac'):.0f}%"
                          for t in ("heur", "adv", "good")})
    print("saved", tab)


if __name__ == "__main__":
    main()
